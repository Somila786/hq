// Builds a single-file Worker at dist/worker.js.
//
// Why this exists: `wrangler deploy` handles multiple ES modules by itself, so
// this is NOT needed for the normal deploy path. It exists for pasting the
// Worker into the Cloudflare dashboard's code editor, which takes one file.
//
// It is a deliberately dumb concatenator, not a real bundler -- there are no
// dependencies to resolve and no transpiling to do. Each module keeps its own
// scope: auth.js goes in at the top level (index.js imports its names
// directly), while db.js and views.js are wrapped in IIFEs so they stay
// namespaced exactly as `db.*` and `views.*`.
//
// Verify the output with:  npm run test:bundle

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (f) => readFileSync(join(ROOT, "src", f), "utf8");

// `export function x`, `export async function x`, `export const x`
function exportedNames(src) {
  const names = new Set();
  for (const m of src.matchAll(/^export\s+(?:async\s+)?function\s+([A-Za-z0-9_$]+)/gm)) names.add(m[1]);
  for (const m of src.matchAll(/^export\s+const\s+([A-Za-z0-9_$]+)/gm)) names.add(m[1]);
  return [...names];
}

const stripExport = (src) => src.replace(/^export\s+/gm, "");

function namespaced(src, name) {
  const names = exportedNames(src);
  if (!names.length) throw new Error(`no exports found in ${name}`);
  return [
    `const ${name} = (() => {`,
    stripExport(src),
    `return { ${names.join(", ")} };`,
    `})();`,
  ].join("\n");
}

const auth = read("auth.js");
const db = read("db.js");
const views = read("views.js");
let index = read("index.js");

// Drop the three import statements; everything they named is inlined below.
index = index.replace(/^import\s+\{[\s\S]*?\}\s+from\s+"\.\/auth\.js";\s*$/m, "");
index = index.replace(/^import\s+\*\s+as\s+db\s+from\s+"\.\/db\.js";\s*$/m, "");
index = index.replace(/^import\s+\*\s+as\s+views\s+from\s+"\.\/views\.js";\s*$/m, "");

if (/^import\s/m.test(index)) {
  throw new Error("index.js still has an unhandled import after stripping");
}

const banner = `// Catalyst 7 KPI -- single-file build, generated by tests/bundle.mjs.
// DO NOT EDIT THIS FILE. Edit src/*.js and rebuild, or your change will be
// lost the next time anyone regenerates it.
//
// Built: ${new Date().toISOString().slice(0, 10)}
// Source: src/auth.js + src/db.js + src/views.js + src/index.js
`;

const out = [
  banner,
  "// ===================== src/auth.js =====================",
  stripExport(auth),
  "// ===================== src/db.js =======================",
  namespaced(db, "db"),
  "// ===================== src/views.js ====================",
  namespaced(views, "views"),
  "// ===================== src/index.js ====================",
  index.trim(),
  "",
].join("\n\n");

mkdirSync(join(ROOT, "dist"), { recursive: true });
writeFileSync(join(ROOT, "dist", "worker.js"), out);

console.log(`dist/worker.js written -- ${out.split("\n").length} lines, ${(out.length / 1024).toFixed(1)} KB`);
console.log(`  auth.js  -> ${exportedNames(auth).length} exports inlined at top level`);
console.log(`  db.js    -> ${exportedNames(db).length} exports namespaced as db.*`);
console.log(`  views.js -> ${exportedNames(views).length} exports namespaced as views.*`);
